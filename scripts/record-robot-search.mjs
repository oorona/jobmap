import {createRequire} from 'node:module';
import {mkdir} from 'node:fs/promises';
const require=createRequire(import.meta.url);
const {chromium}=require('../frontend/node_modules/@playwright/test');
await mkdir('artifacts',{recursive:true});
const browser=await chromium.launch({headless:true});
const context=await browser.newContext({viewport:{width:1280,height:960},recordVideo:{dir:'/tmp/jobmap-recording',size:{width:1280,height:960}}});
const page=await context.newPage();
const errors=[];
page.on('pageerror',e=>errors.push(e.message));
try{
 await page.goto('https://jobmap.home.iktdts.com/',{waitUntil:'networkidle'});
 await page.getByRole('button',{name:'Usage & costs',exact:true}).click();
 await page.getByRole('region',{name:'Jev costs'}).getByText('Today',{exact:false}).waitFor();
 await page.getByRole('button',{name:'Discover',exact:true}).click();
 await page.locator('.bubble').first().waitFor();
 await page.waitForTimeout(1600);
 const response=page.waitForResponse(r=>r.url().endsWith('/api/search/refine')&&r.request().method()==='POST',{timeout:35000});
 await page.getByRole('textbox',{name:'Search jobs'}).pressSequentially('I want to build robot',{delay:110});
 const result=await (await response).json();
 if(!result.available)throw new Error('Live refinement unavailable');
 await page.getByText('Refined with Jev',{exact:true}).waitFor();
 const matches=await page.locator('.job-row').count();
 if(!matches||matches>30)throw new Error('Expected a relevant subset');
 await page.waitForTimeout(1200);
 await page.evaluate(()=>window.scrollTo({top:document.querySelector('.discovery').getBoundingClientRect().top+window.scrollY-15,behavior:'smooth'}));
 await page.waitForTimeout(2500);
 await page.locator('.job-row').first().locator('.job-main').click();
 await page.getByRole('heading',{name:'Evidence',exact:true}).waitFor();
 await page.waitForTimeout(1800);
 await page.getByRole('button',{name:'Close details'}).click();
 await page.evaluate(()=>window.scrollTo({top:0,behavior:'smooth'}));
 await page.getByRole('button',{name:'Usage & costs',exact:true}).click();
 await page.getByRole('button',{name:'Refresh costs'}).click();
 await page.waitForTimeout(1800);
 if(errors.length)throw new Error(errors.join('\n'));
 await context.close();
 await page.video().saveAs('artifacts/jobmap-robot-search.webm');
 console.log(JSON.stringify({saved:'artifacts/jobmap-robot-search.webm',matches,browserErrors:0}));
}finally{await browser.close();}
